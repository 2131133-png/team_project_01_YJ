// 진단 결과별로 먼저 보여 주는 질문(결과 화면 아래 질문 버튼 순서)
const FIRST = {
  fraud: [2, 1, 3, 7, 5, 18],
  dispute: [8, 9, 3, 4, 5, 18],
  mistransfer: [15, 12, 5],
  phishing: [16, 12],
  other: [12, 5, 18],
};

// classify() 결과 → 위 FIRST 의 열쇠
export function resultKey(c = {}) {
  if (c.result === 'fraud') return 'fraud';
  if (c.result === 'dispute') return 'dispute';
  if (c.result === 'out') return c.variant === 'mistransfer' ? 'mistransfer' : 'phishing';
  return 'other';
}

const byId = (id) => FAQS.find((f) => f.id === id);
export const faqById = byId;
export const faqList = (key) => (FIRST[key] || FIRST.other).map((id) => ({ id, q: byId(id).q }));

// 점수 = 맞은 단어 글자 수의 합, 진단 결과에 맞는 질문이면 1점 더. 맞은 단어가 없으면 null
export function matchFaq(text, key) {
  const t = String(text).replace(/\s+/g, ' ');
  const first = FIRST[key] || FIRST.other;
  let best = null;
  for (const f of FAQS) {
    const hit = f.keywords.filter((k) => t.includes(k));
    if (!hit.length) continue;
    const score = hit.reduce((n, k) => n + k.length, 0) + (first.includes(f.id) ? 1 : 0);
    if (!best || score > best.score) best = { faq: f, score };
  }
  return best ? best.faq : null;
}

// 화면에 돌려줄 답 한 건: 문장·바로 연결·관련 질문
export function faqReply(f, key) {
  const lines = (f.byResult?.[key === 'dispute' ? 'dispute' : ''] || f.answer);
  const related = faqList(key).filter((x) => x.id !== f.id).slice(0, 4);
  return {
    answer: lines.map((l) => `· ${l}`).join('\n'),
    notice: '※ 참고 정보이며 법적 판단이 아니에요.',
    links: f.links || [],
    related,
  };
}

